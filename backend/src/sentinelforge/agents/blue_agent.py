"""SentinelForge Phase 5 — Blue Agent Analyst & Detection Remediation Pipeline

Consumes detection outcomes generated by DetectionGapEvaluator, analyzes detection gaps,
derives evidence-backed candidate Sigma rules with immutable provenance, validates syntax
and false-positive immunity in a telemetry-only sandbox, and orchestrates authorized retesting
through the existing security boundaries.

SECURITY INVARIANTS:
- Blue Agent is UNTRUSTED.
- MUST NOT execute system commands directly.
- MUST NOT create SignedBlueprint objects or invoke BlueprintSigner.
- MUST NOT bypass ExperimentSafetyBoundary or PolicyEngine.
- MUST NOT manufacture RetestResult objects or directly transition ExerciseStateMachine to VERIFIED.
- All candidate rules MUST preserve x-sentinelforge provenance.
- Overly broad rules and false positives MUST be strictly rejected.
"""

